import 'package:devsync/core/animations/app_animations.dart';
import 'package:flutter/material.dart';

// Subtle scale press feedback wrapper for interactive cards and buttons.
class AppScaleTap extends StatefulWidget {
  const AppScaleTap({
    super.key,
    required this.child,
    this.onTap,
    this.pressedScale = 0.97,
  });

  final Widget child;
  final VoidCallback? onTap;
  final double pressedScale;

  @override
  State<AppScaleTap> createState() => _AppScaleTapState();
}

class _AppScaleTapState extends State<AppScaleTap> {
  bool _pressed = false;

  @override
  Widget build(BuildContext context) {
    return GestureDetector(
      behavior: HitTestBehavior.opaque,
      onTapDown: (_) => setState(() => _pressed = true),
      onTapUp: (_) => setState(() => _pressed = false),
      onTapCancel: () => setState(() => _pressed = false),
      onTap: widget.onTap,
      child: AnimatedScale(
        scale: _pressed ? widget.pressedScale : 1.0,
        duration: AppAnimations.fast,
        curve: AppAnimations.easeOut,
        child: widget.child,
      ),
    );
  }
}
